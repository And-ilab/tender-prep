/**
 * @param {{ includeHeader?: boolean }} [opts]
 * @returns {string}
 */
export function buildTenderDocumentFormattingPromptSection(opts = {}) {
  const includeHeader = opts.includeHeader !== false;
  if (!includeHeader) {
    return TENDER_DOCUMENT_FORMATTING_SPEC;
  }
  return [TENDER_DOCUMENT_FORMATTING_SECTION_HEADER, "", TENDER_DOCUMENT_FORMATTING_SPEC].join("\n");
}
